import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packagePath = path.join(root, 'package.json');
const pkg = JSON.parse(fs.readFileSync(packagePath, 'utf8'));
const next = process.argv[2] || pkg.version.split('.').map((n, index) => index === 2 ? Number(n) + 1 : n).join('.');
if (!/^\d+\.\d+\.\d+$/.test(next)) throw new Error('Use uma versão no formato 1.2.3');
const build = next + '-' + new Date().toISOString().replace(/[-:.TZ]/g, '');
pkg.version = next;
fs.writeFileSync(packagePath, JSON.stringify(pkg, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'version.js'), `// Generated by scripts/release.mjs\nexport const APP_VERSION = '${next}';\nexport const BUILD_ID = '${build}';\n`);
fs.writeFileSync(path.join(root, 'version.json'), JSON.stringify({version:next,build}) + '\n');
for (const file of fs.readdirSync(root)) {
  if (!/\.(js|html)$/.test(file)) continue;
  const target = path.join(root, file);
  let source = fs.readFileSync(target, 'utf8');
  source = source.replace(/\?v=\d+\.\d+\.\d+/g, '?v=' + next);
  if (file === 'index.html') source = source.replace(/(<span id="app-version" class="version">)(?:Conferindo versão|Versão \d+\.\d+\.\d+)(<\/span>)/, (_, open, close) => open + 'Versão ' + next + close);
  if (file === 'sw.js') source = source.replace(/const CACHE = '[^']+';/, `const CACHE = 'predify-shell-${build}';`);
  fs.writeFileSync(target, source);
}
console.log(JSON.stringify({version:next,build}));
